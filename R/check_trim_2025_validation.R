stopifnot(endpoint_2000_decision(-100,rep(-100,500))$gate=='geen_2000_interval_constante_verdeling')
stopifnot(endpoint_2000_decision(NA_real_,seq(-20,20,length.out=500))$gate=='geen_2000_langemaat')
d<-endpoint_2000_decision(0,c(rep(-20,250),seq(0,100,length.out=250)));stopifnot(d$gate=='kandidaat_2000_validatie',!d$latest_stable)
